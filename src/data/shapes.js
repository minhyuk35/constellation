// Coordinates use a square illustration space: x right, y up. The constellation
// projections preserve the reference paths in the original demo (d3-celestial).
const points = (pairs) => pairs.map(([x, y]) => ({ x, y }));
const chain = (n, closed = false) =>
  Array.from({ length: closed ? n : n - 1 }, (_, i) => [i, (i + 1) % n]);
function shape(id, name, english, tile, pairs, description, options = {}) {
  return {
    id,
    name,
    english,
    tile,
    points: points(pairs),
    edges: chain(pairs.length, true),
    description,
    category: 'object',
    kind: '상상의 모양',
    ...options,
  };
}
const radial = (n, radius) =>
  Array.from({ length: n }, (_, i) => {
    const a = Math.PI / 2 + (i * Math.PI * 2) / n;
    const r = typeof radius === 'function' ? radius(i, a) : radius;
    return [Math.cos(a) * r, Math.sin(a) * r];
  });

